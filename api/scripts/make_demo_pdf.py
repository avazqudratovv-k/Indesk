def download_font(dest_dir: Path) -> Path:
    dest = dest_dir / "NotoSansKR.ttf"
    with urllib.request.urlopen(FONT_URL, timeout=60) as resp:  # noqa: S310  # fixed https URL
        dest.write_bytes(resp.read())
    return dest


def build_pdf(path: Path, lang: str, c: dict[str, Any]) -> None:
    """Write one PDF with the fixed 8-page layout that write_truth() records page numbers for."""
    t = TEXT[lang]
    s = sentences(lang, c)
    body = ParagraphStyle("body", fontName=FONT_NAME, fontSize=11, leading=17, spaceAfter=8)
    h1 = ParagraphStyle("h1", parent=body, fontSize=17, leading=24, spaceAfter=12)
    cover = ParagraphStyle("cover", parent=body, fontSize=24, leading=34, spaceBefore=90, spaceAfter=24)
    small = ParagraphStyle("small", parent=body, fontSize=10, leading=15)
    table_style = TableStyle(
        [
            ("FONTNAME", (0, 0), (-1, -1), FONT_NAME),
            ("FONTSIZE", (0, 0), (-1, -1), 10.5),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eeeeee")),
            ("ALIGN", (-2, 1), (-1, -1), "RIGHT"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]
    )

    def footer(canvas: Any, doc: Any) -> None:
        canvas.saveState()
        canvas.setFont(FONT_NAME, 8)
        canvas.drawString(20 * mm, 17 * mm, t["notice"])
        canvas.drawString(20 * mm, 12.5 * mm, t["source"])
        canvas.drawRightString(190 * mm, 8 * mm, f"{t['page']} {doc.page}")
        canvas.restoreState()

    doc = BaseDocTemplate(
        str(path),
        pagesize=A4,
        title=t["title"],
        author="Indesk",
        leftMargin=20 * mm,
        rightMargin=20 * mm,
    )
    doc.addPageTemplates(
        [PageTemplate(id="p", frames=[Frame(20 * mm, 25 * mm, 170 * mm, 245 * mm, id="f")], onPage=footer)]
    )

    def paras(key: str) -> list[Any]:
        return [Paragraph(x, body) for x in s[key]]

    def table(data: list[list[str]], widths: list[float]) -> Table:
        tb = Table(data, colWidths=[w * mm for w in widths], hAlign="LEFT")
        tb.setStyle(table_style)
        return tb

    line_data = [[t["line"], t["boardings"], t["alightings"]]]
    line_data += [[ln, fmt_int(c["line_b"][ln]), fmt_int(c["line_a"][ln])] for ln in LINES]
    line_data.append(["1/2/3/7", fmt_int(c["total_b"]), fmt_int(c["total_a"])])
    top_data = [[t["rank"], t["station"], t["boardings"]]]
    top_data += [[str(i), name, fmt_int(v)] for i, (name, v) in enumerate(c["top"], 1)]
    wd_data = [
        [t["metric"], t["value"]],
        [("Weekdays (days)" if lang == "en" else "평일 일수"), str(c["weekday_days"])],
        [("Weekday average boardings per day" if lang == "en" else "평일 하루 평균 승차"), fmt_dec(c["weekday_avg"])],
        [("Weekend days" if lang == "en" else "주말 일수"), str(c["weekend_days"])],
        [("Weekend average boardings per day" if lang == "en" else "주말 하루 평균 승차"), fmt_dec(c["weekend_avg"])],
    ]
    day_data = [
        [t["metric"], t["date"], t["boardings"]],
        [("Busiest" if lang == "en" else "가장 많은 날"), date_label(c["busiest"][0], lang), fmt_int(c["busiest"][1])],
        [("Quietest" if lang == "en" else "가장 적은 날"), date_label(c["quietest"][0], lang), fmt_int(c["quietest"][1])],
    ]

    story: list[Any] = [
        Paragraph(t["title"], cover),
        Paragraph(t["notice"], body),
        Paragraph(t["source"], body),
        PageBreak(),
        Paragraph(t["h_scope"], h1),
        *paras("scope"),
        PageBreak(),
        Paragraph(t["h_lines"], h1),
        *paras("lines"),
        table(line_data, [45, 55, 55]),
        PageBreak(),
        Paragraph(t["h_top"], h1),
        *paras("top"),
        table(top_data, [20, 80, 55]),
        PageBreak(),
        Paragraph(t["h_wd"], h1),
        *paras("wd"),
        table(wd_data, [95, 60]),
        PageBreak(),
        Paragraph(t["h_days"], h1),
        *paras("days"),
        table(day_data, [35, 80, 40]),
        PageBreak(),
        Paragraph(t["h_method"], h1),
        *[Paragraph(x, body) for x in s["method"]],
        PageBreak(),
        Paragraph(t["h_tables"], h1),
    ]
    sc_data = [[t["line"], t["stations_col"], t["rows_col"], t["boardings"], t["alightings"]]]
    for ln in LINES:
        sc_data.append(
            [
                ln,
                str(c["line_station_counts"][ln]),
                fmt_int(c["line_rows"][ln]),
                fmt_int(c["line_b"][ln]),
                fmt_int(c["line_a"][ln]),
            ]
        )
    story += [table(sc_data, [20, 25, 25, 45, 45]), Spacer(1, 6 * mm), Paragraph(CSV_NAME, small)]
    doc.build(story)


def write_truth(path: Path, c: dict[str, Any]) -> None:
    # Page numbers are the fixed layout above: 1 cover, 2 scope, 3 lines, 4 top 10, 5 weekday/weekend,
    # 6 busiest/quietest, 7 method, 8 tables by line. They are the same in both languages.
    def item(value: Any, method: str, pages: list[int]) -> dict[str, Any]:
        return {"value": value, "method": method, "pages": pages}

    bd, bv = c["busiest"]
    qd, qv = c["quietest"]
    truth = {
        "source_file": CSV_NAME,
        "note": "Page numbers are the same in the ko and en PDFs. Holidays are counted as weekdays.",
        "scope": {
            "rows": item(c["rows"], "count of data rows", [2, 8]),
            "days": item(c["days"], "distinct 사용일자", [2]),
            "first_day": item(c["first_day"].isoformat(), "min 사용일자", [2]),
            "last_day": item(c["last_day"].isoformat(), "max 사용일자", [2]),
            "unique_station_names": item(c["unique_stations"], "distinct 역명 over all lines", [2]),
            "line_station_pairs": item(c["line_station_pairs"], "distinct (노선명, 역명) pairs", [2]),
        },
        "totals": {
            "boardings_all_lines": item(c["total_b"], "sum 승차총승객수 over all rows", [3]),
            "alightings_all_lines": item(c["total_a"], "sum 하차총승객수 over all rows", [3]),
        },
        "by_line": {
            ln: {
                "boardings": item(c["line_b"][ln], f"sum 승차총승객수 where 노선명={ln}", [3, 8]),
                "alightings": item(c["line_a"][ln], f"sum 하차총승객수 where 노선명={ln}", [3, 8]),
                "rows": item(c["line_rows"][ln], f"row count where 노선명={ln}", [8]),
                "stations": item(c["line_station_counts"][ln], f"distinct 역명 where 노선명={ln}", [8]),
            }
            for ln in LINES
        },
        "top10_stations_by_boardings": [
            item({"rank": i, "station": name, "boardings": v}, "sum 승차총승객수 grouped by 역명, sorted desc", [4])
            for i, (name, v) in enumerate(c["top"], 1)
        ],
        "weekday_weekend": {
            "weekday_days": item(c["weekday_days"], "days Monday to Friday, holidays included", [5]),
            "weekday_total_boardings": item(c["weekday_total"], "sum of daily boardings on weekdays", [5]),
            "weekday_avg_boardings_per_day": item(
                round(c["weekday_avg"], 2), "weekday_total / weekday_days, 2 decimals", [5]
            ),
            "weekend_days": item(c["weekend_days"], "days Saturday and Sunday", [5]),
            "weekend_total_boardings": item(c["weekend_total"], "sum of daily boardings on weekend days", [5]),
            "weekend_avg_boardings_per_day": item(
                round(c["weekend_avg"], 2), "weekend_total / weekend_days, 2 decimals", [5]
            ),
        },
        "busiest_quietest_day": {
            "busiest_day": item({"date": bd.isoformat(), "boardings": bv}, "max of daily boardings over all lines", [6]),
            "quietest_day": item({"date": qd.isoformat(), "boardings": qv}, "min of daily boardings over all lines", [6]),
        },
    }
    path.write_text(json.dumps(truth, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    c = compute(args.csv)
    with tempfile.TemporaryDirectory() as tmp:
        font = download_font(Path(tmp))
        pdfmetrics.registerFont(TTFont(FONT_NAME, str(font)))
        for lang in ("ko", "en"):
            build_pdf(args.out / f"seoul_subway_2026-09_summary_{lang}.pdf", lang, c)
    write_truth(args.out / "seoul_subway_2026-09_summary_truth.json", c)
    print("done")


if __name__ == "__main__":
    main()
