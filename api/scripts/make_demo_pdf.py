def fmt_int(n: int) -> str:
    return f"{n:,}"


def fmt_dec(x: float) -> str:
    return f"{x:,.2f}"


def date_label(d: dt.date, lang: str) -> str:
    if lang == "ko":
        names = "월화수목금토일"
        return f"{d.year}년 {d.month}월 {d.day}일 ({names[d.weekday()]})"
    return f"{d.strftime('%A')}, {d.strftime('%B')} {d.day}, {d.year}"


def compute(csv_path: Path) -> dict[str, Any]:
    with csv_path.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.reader(fh))
    header, body = rows[0], rows[1:]
    ix = {name: i for i, name in enumerate(header)}
    line_b: dict[str, int] = defaultdict(int)
    line_a: dict[str, int] = defaultdict(int)
    line_rows: dict[str, int] = defaultdict(int)
    line_stations: dict[str, set[str]] = defaultdict(set)
    station_b: dict[str, int] = defaultdict(int)
    day_b: dict[dt.date, int] = defaultdict(int)
    for r in body:
        d = dt.datetime.strptime(r[ix["사용일자"]], "%Y%m%d").date()
        line, station = r[ix["노선명"]], r[ix["역명"]]
        b, a = int(r[ix["승차총승객수"]]), int(r[ix["하차총승객수"]])
        line_b[line] += b
        line_a[line] += a
        line_rows[line] += 1
        line_stations[line].add(station)
        station_b[station] += b
        day_b[d] += b
    top = sorted(station_b.items(), key=lambda kv: (-kv[1], kv[0]))[:10]
    if top[9][1] == sorted(station_b.values(), reverse=True)[10]:
        raise SystemExit("tie at rank 10: top-10 list would be ambiguous")
    weekdays = {d: v for d, v in day_b.items() if d.weekday() < 5}
    weekends = {d: v for d, v in day_b.items() if d.weekday() >= 5}
    busiest = max(day_b.items(), key=lambda kv: kv[1])
    quietest = min(day_b.items(), key=lambda kv: kv[1])
    return {
        "rows": len(body),
        "days": len(day_b),
        "first_day": min(day_b),
        "last_day": max(day_b),
        "line_b": dict(line_b),
        "line_a": dict(line_a),
        "line_rows": dict(line_rows),
        "line_station_counts": {k: len(v) for k, v in line_stations.items()},
        "unique_stations": len({s for v in line_stations.values() for s in v}),
        "line_station_pairs": sum(len(v) for v in line_stations.values()),
        "total_b": sum(line_b.values()),
        "total_a": sum(line_a.values()),
        "top": top,
        "weekday_days": len(weekdays),
        "weekday_total": sum(weekdays.values()),
        "weekday_avg": sum(weekdays.values()) / len(weekdays),
        "weekend_days": len(weekends),
        "weekend_total": sum(weekends.values()),
        "weekend_avg": sum(weekends.values()) / len(weekends),
        "busiest": busiest,
        "quietest": quietest,
    }


